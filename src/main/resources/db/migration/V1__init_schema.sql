-- V1__init_schema.sql
-- Initial schema for Solar & Battery Sizing Assistant

-- 1. Users
CREATE TABLE users (
                       id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
                       email VARCHAR(255) NOT NULL UNIQUE,
                       password_hash VARCHAR(255) NOT NULL,
                       display_name VARCHAR(100) NOT NULL,
                       role VARCHAR(20) NOT NULL DEFAULT 'USER',
                       created_at TIMESTAMP NOT NULL DEFAULT now(),
                       CONSTRAINT chk_users_role CHECK (role IN ('USER', 'ADMIN'))
);

-- 2. Device Categories
CREATE TABLE device_categories (
                                   id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                   name VARCHAR(60) NOT NULL UNIQUE,
                                   icon VARCHAR(40) NOT NULL
);

-- 3. Devices (System catalog + user custom devices)
CREATE TABLE devices (
                         id BIGSERIAL PRIMARY KEY,
                         category_id SMALLINT NOT NULL REFERENCES device_categories(id),
                         name VARCHAR(120) NOT NULL,
                         typical_watts NUMERIC(8,1) NOT NULL,
                         surge_multiplier NUMERIC(3,1) NOT NULL DEFAULT 1.0,
                         duty_cycle NUMERIC(3,2) NOT NULL DEFAULT 1.00,
                         default_hours_per_day NUMERIC(4,1) NOT NULL,
                         source_note TEXT,
                         is_custom BOOLEAN NOT NULL DEFAULT FALSE,
                         created_by UUID REFERENCES users(id) ON DELETE CASCADE
);

-- 4. Locations
CREATE TABLE locations (
                           id BIGSERIAL PRIMARY KEY,
                           name VARCHAR(120) NOT NULL,
                           country VARCHAR(60) NOT NULL,
                           latitude NUMERIC(8,5) NOT NULL,
                           longitude NUMERIC(8,5) NOT NULL,
                           timezone VARCHAR(50) NOT NULL
);

-- 5. Cached Typical-Day Irradiance (288 rows per location: 12 months x 24 hours)
CREATE TABLE irradiance_typical_day (
                                        location_id BIGINT NOT NULL REFERENCES locations(id) ON DELETE CASCADE,
                                        month SMALLINT NOT NULL CHECK (month BETWEEN 1 AND 12),
    hour SMALLINT NOT NULL CHECK (hour BETWEEN 0 AND 23),
    ghi_w_m2 NUMERIC(7,2) NOT NULL,
    temp_c NUMERIC(4,1) NOT NULL,
    PRIMARY KEY (location_id, month, hour)
);

-- 6. Grid Outage Profiles (for Hybrid mode)
CREATE TABLE grid_outage_profiles (
                                      id BIGSERIAL PRIMARY KEY,
                                      name VARCHAR(80) NOT NULL,
                                      outages_per_month SMALLINT NOT NULL,
                                      avg_duration_hours NUMERIC(4,1) NOT NULL,
                                      typical_start_hour SMALLINT NOT NULL CHECK (typical_start_hour BETWEEN 0 AND 23),
                                      is_preset BOOLEAN NOT NULL DEFAULT FALSE
);

-- 7. Hardware Catalogs
CREATE TABLE panel_catalog (
                               id BIGSERIAL PRIMARY KEY,
                               brand VARCHAR(80) NOT NULL,
                               model VARCHAR(100) NOT NULL,
                               rated_watts NUMERIC(7,1) NOT NULL,
                               vmp NUMERIC(6,2) NOT NULL,
                               voc NUMERIC(6,2) NOT NULL,
                               imp NUMERIC(6,2) NOT NULL,
                               isc NUMERIC(6,2) NOT NULL,
                               temp_coeff_pmax NUMERIC(5,3) NOT NULL,
                               efficiency_pct NUMERIC(5,2) NOT NULL,
                               price NUMERIC(10,2) NOT NULL
);

CREATE TABLE battery_catalog (
                                 id BIGSERIAL PRIMARY KEY,
                                 brand VARCHAR(80) NOT NULL,
                                 model VARCHAR(100) NOT NULL,
                                 chemistry VARCHAR(20) NOT NULL,
                                 nominal_voltage NUMERIC(6,2) NOT NULL,
                                 capacity_kwh NUMERIC(7,2) NOT NULL,
                                 usable_dod_pct NUMERIC(5,2) NOT NULL,
                                 round_trip_eff_pct NUMERIC(5,2) NOT NULL,
                                 cycle_life INT NOT NULL,
                                 annual_fade_pct NUMERIC(4,2) NOT NULL,
                                 price NUMERIC(10,2) NOT NULL,
                                 CONSTRAINT chk_battery_chemistry CHECK (chemistry IN ('LFP', 'AGM', 'NMC'))
);

CREATE TABLE inverter_catalog (
                                  id BIGSERIAL PRIMARY KEY,
                                  brand VARCHAR(80) NOT NULL,
                                  model VARCHAR(100) NOT NULL,
                                  type VARCHAR(20) NOT NULL,
                                  continuous_w INT NOT NULL,
                                  surge_w INT NOT NULL,
                                  efficiency_pct NUMERIC(5,2) NOT NULL,
                                  mppt_v_min NUMERIC(6,1) NOT NULL,
                                  mppt_v_max NUMERIC(6,1) NOT NULL,
                                  battery_voltage NUMERIC(6,2),
                                  price NUMERIC(10,2) NOT NULL,
                                  CONSTRAINT chk_inverter_type CHECK (type IN ('GRID_TIED', 'OFF_GRID', 'HYBRID'))
);

-- 8. Projects
CREATE TABLE projects (
                          id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
                          user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                          name VARCHAR(120) NOT NULL,
                          system_mode VARCHAR(12) NOT NULL,
                          location_id BIGINT NOT NULL REFERENCES locations(id),
                          load_input_method VARCHAR(10) NOT NULL,
                          manual_daily_kwh NUMERIC(8,2),
                          autonomy_days NUMERIC(3,1),
                          backup_hours_target NUMERIC(4,1),
                          outage_profile_id BIGINT REFERENCES grid_outage_profiles(id),
                          tariff_per_kwh NUMERIC(8,3) NOT NULL,
                          feed_in_per_kwh NUMERIC(8,3) NOT NULL DEFAULT 0,
                          panel_id BIGINT REFERENCES panel_catalog(id),
                          battery_id BIGINT REFERENCES battery_catalog(id),
                          tilt_deg NUMERIC(4,1),
                          azimuth_deg NUMERIC(5,1) NOT NULL DEFAULT 0,
                          system_losses_pct NUMERIC(4,1) NOT NULL DEFAULT 14.0,
                          created_at TIMESTAMP NOT NULL DEFAULT now(),
                          updated_at TIMESTAMP NOT NULL DEFAULT now(),
                          CONSTRAINT chk_projects_system_mode CHECK (system_mode IN ('ON_GRID', 'OFF_GRID', 'HYBRID')),
                          CONSTRAINT chk_projects_load_method CHECK (load_input_method IN ('MANUAL', 'DEVICES'))
);

-- 9. Project Devices
CREATE TABLE project_devices (
                                 id BIGSERIAL PRIMARY KEY,
                                 project_id UUID NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
                                 device_id BIGINT NOT NULL REFERENCES devices(id),
                                 quantity SMALLINT NOT NULL DEFAULT 1,
                                 hours_per_day NUMERIC(4,1) NOT NULL,
                                 start_hour SMALLINT CHECK (start_hour BETWEEN 0 AND 23),
                                 always_on BOOLEAN NOT NULL DEFAULT FALSE
);

-- 10. Simulations
CREATE TABLE simulations (
                             id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
                             project_id UUID NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
                             label VARCHAR(80) NOT NULL,
                             status VARCHAR(12) NOT NULL,
                             run_at TIMESTAMP NOT NULL DEFAULT now(),
                             daily_load_kwh NUMERIC(8,2) NOT NULL,
                             peak_load_w NUMERIC(9,1) NOT NULL,
                             pv_kwp NUMERIC(7,2) NOT NULL,
                             panel_count INT NOT NULL,
                             battery_kwh NUMERIC(8,2) NOT NULL,
                             battery_count INT NOT NULL,
                             inverter_continuous_w INT NOT NULL,
                             inverter_surge_w INT NOT NULL,
                             controller_amps NUMERIC(6,1) NOT NULL,
                             annual_pv_kwh NUMERIC(10,1) NOT NULL,
                             self_consumption_pct NUMERIC(5,2) NOT NULL,
                             grid_import_kwh NUMERIC(10,1) NOT NULL,
                             grid_export_kwh NUMERIC(10,1) NOT NULL,
                             unmet_load_kwh NUMERIC(10,1) NOT NULL DEFAULT 0,
                             capex NUMERIC(12,2) NOT NULL,
                             annual_savings NUMERIC(12,2) NOT NULL,
                             payback_years NUMERIC(5,1),
                             assumptions_json JSONB NOT NULL,
                             CONSTRAINT chk_simulations_status CHECK (status IN ('COMPLETED', 'FAILED'))
);

-- 11. Simulation Hourly Results (288 rows per simulation: 12 months x 24 hours)
CREATE TABLE simulation_hourly (
                                   simulation_id UUID NOT NULL REFERENCES simulations(id) ON DELETE CASCADE,
                                   month SMALLINT NOT NULL CHECK (month BETWEEN 1 AND 12),
    hour SMALLINT NOT NULL CHECK (hour BETWEEN 0 AND 23),
    load_w NUMERIC(9,1) NOT NULL,
    pv_w NUMERIC(9,1) NOT NULL,
    battery_soc_pct NUMERIC(5,2) NOT NULL,
    grid_import_w NUMERIC(9,1) NOT NULL,
    grid_export_w NUMERIC(9,1) NOT NULL,
    unmet_w NUMERIC(9,1) NOT NULL,
    PRIMARY KEY (simulation_id, month, hour)
);

-- Key Indexes
CREATE INDEX idx_devices_name ON devices(name);
CREATE INDEX idx_devices_category_id ON devices(category_id);
CREATE INDEX idx_projects_user_id ON projects(user_id);
CREATE INDEX idx_project_devices_project_id ON project_devices(project_id);
CREATE INDEX idx_simulations_project_id ON simulations(project_id);